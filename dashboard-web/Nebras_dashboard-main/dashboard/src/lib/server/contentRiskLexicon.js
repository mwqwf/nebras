/** تطبيع عربيّ/لاتينيّ خفيف: توحيد الألف/الياء/الهاء، إزالة التشكيل والرموز. */
export function normalizeForMatch(input) {
	return String(input || '')
		.toLowerCase()
		.replace(/[ً-ٰٟ]/g, '') // التشكيل
		.replace(/[إأآا]/g, 'ا')
		.replace(/ى/g, 'ي')
		.replace(/ة/g, 'ه')
		.replace(/ـ/g, '') // التطويل
		.replace(/[^\p{L}\p{N}\s]/gu, ' ') // رموز → مسافات
		.replace(/\s+/g, ' ')
		.trim();
}

